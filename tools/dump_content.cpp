namespace {
std::string slug(std::string_view s) {
    std::string id;
    for (char c : s) {
        if (c == '\'') continue;
        id += c == ' ' || c == '-' ? '_' : char(std::tolower(static_cast<unsigned char>(c)));
    }
    return id;
}
void skill(const SkillDef& d, Element e, std::string_view owner) {
    if (d.name.empty()) return;
    std::println("skill\t{}\t{}\t{}\t{}{}", slug(d.name), element_name(e), d.name, d.desc, owner);
}
}  // namespace

int main(int argc, char** argv) {
    if (argc > 1 && std::string_view(argv[1]) == "--interactions") {  // [U-397] → docs/INTERACTIONS.md
        std::println("# Interactions (generated by `./build/dump_content --interactions` from the game's tables)\n");
        for (const std::string& l : interaction_lines()) std::println("{}", l.starts_with("## ") ? "\n" + l + "\n" : "- " + l);
        return 0;
    }
    if (argc > 2 && std::string_view(argv[1]) == "--check-version") {  // [U-478] apply a version, print its mods / items
        int n = 0;
        const std::string err = apply_version(argv[2], &n);
        if (!err.empty()) {
            std::println("ERROR {}", err);
            return 1;
        }
        std::println("ok {} ({} changes), pack '{}', linked '{}', mod lol: {}", current_version(), n, version_pack_dir(), version_linked_pack(), mod_enabled("lol"));
        for (const ItemDef& d : kItems)
            if (!d.mod.empty()) std::println("  mod item {} [{}] available: {}", d.name, d.mod, item_available(d, 0, 0));
        // [U-483] the setup tables as this version has them
        auto m = [](const StatMod& x) {
            return x.key == StatKey::Count ? std::string("-") : std::format("{}{:+g}{} {}", "", x.value / 100.0, x.pct ? "%" : "", kStatKeyNames[int(x.key)]);
        };
        for (const KeystoneDef& k : keystones())
            if (!k.name.empty()) std::println("  keystone {}  [{}]", k.name, m(k.mod));
        for (const SpecTree& t : spec_trees())
            if (!t.name.empty()) {
                std::string ns;
                for (const auto& tier : t.tiers)
                    for (const SpecNode& nd : tier) ns += nd.name.empty() ? std::string(" (none)") : std::format(" {}[{}]", nd.name, m(nd.mod));
                std::println("  tree {} ({}):{}", t.name, t.theme, ns);
            }
        for (int r = 0; r < 3; ++r) {
            std::string ns;
            for (const RuneDef& d : shards()[std::size_t(r)])
                if (!d.name.empty()) ns += std::format(" {}[{}]", d.name, m(d.mod));
            std::println("  shards {}:{}", kRuneSlotNames[r], ns);
        }
        std::string qs;
        for (const RuneDef& d : quints())
            if (!d.name.empty()) qs += std::format(" {}[{}]", d.name, m(d.mod));
        std::println("  quints:{}", qs);
        for (const MasteryTree& t : mastery_trees()) {
            std::string ns;
            for (const MasteryDef& d : t.tiers[0]) if (d.max_rank) ns += std::format(" {}x{}[{}]", d.name, d.max_rank, m(d.mod));
            ns += "  | tier 5:";
            for (const MasteryDef& d : t.tiers[4]) if (d.max_rank) ns += std::format(" {}x{}[{}]", d.name, d.max_rank, m(d.mod));
            std::println("  masteries {} tier 1:{}", t.name, ns);
        }
        return 0;
    }
    if (argc > 2 && std::string_view(argv[1]) == "--check-champ") {  // [U-460] parse an own champion file, print what it became
        std::ifstream in(argv[2]);
        std::stringstream ss;
        ss << in.rdbuf();
        static ChampionDef c{};
        const std::string err = parse_champion_text(ss.str(), c);
        if (!err.empty()) {
            std::println("ERROR {}", err);
            return 1;
        }
        std::println("ok {}", c.name);
        for (const SkillDef* d : {&c.p, &c.w, &c.e, &c.r, &c.t, &c.y}) {
            std::println("  {}: kind {} casts {} stages {}/{}/{} tether {} pull {} free {} vis {:06x}", d->name, int(d->kind), d->casts,
                         int(d->stages[0].kind), int(d->stages[1].kind), int(d->stages[2].kind), d->tether_ms, d->pull, d->free_cast,
                         d->vis.colour);
        }
        return 0;
    }
    for (const ChampionDef& c : champions()) {
        std::println("champion\t{}\t{}\t{}\t{} {}\t{:06x}\t{:06x}\t{}", slug(c.name), element_name(c.element), c.name, role_name(c.role),
                     c.body == &kBroadBody ? "broad" : c.body == &kSlimBody ? "slim" : "humanoid", c.colour, element_colour(c.element),
                     c.avatar ? "avatar" : "");
        for (const SkillDef* s : {&c.p, &c.w, &c.e, &c.r, &c.t, &c.y}) skill(*s, c.element, "");
    }
    for (int q = 0; q < int(q_options().size()); ++q) skill(q_options()[std::size_t(q)], q_option_element(q), "");
    for (const data::SpecialRow& r : data::kSpecialRows) skill(r.def, r.element, "");
    for (const ItemDef& i : kItems) std::println("item\t{}\tNone\t{}\t", slug(i.name), i.name);
    // [U-432] runes + masteries (icons for the setup editor)
    for (const auto& sec : classic_runes())
        for (const RuneDef& r : sec)
            if (!r.name.empty()) std::println("rune\t{}\tNone\t{}\t", slug(r.name), r.name);
    for (const RuneDef& r : quints())
        if (!r.name.empty()) std::println("rune\t{}\tNone\t{}\t", slug(r.name), r.name);
    for (const MasteryTree& t : mastery_trees())
        for (const auto& tier : t.tiers)
            for (const MasteryDef& m : tier)
                if (m.max_rank) std::println("mastery\t{}\tNone\t{}\t{}", slug(m.name), m.name, t.name);
    // [U-304] hitbox circles (forward, side, radius in game units) → tools/art builds models that match them
    for (const auto& [name, b] : {std::pair{"humanoid", &kHumanoidBody}, {"slim", &kSlimBody}, {"broad", &kBroadBody},
                                  {"minion", &kMinionBody}, {"beast", &kBeastBody}}) {
        std::string parts;
        for (int i = 0; i < b->n; ++i)
            parts += std::format("{}{},{},{}", i ? ";" : "", b->parts[std::size_t(i)].fwd, b->parts[std::size_t(i)].side, b->parts[std::size_t(i)].r);
        std::println("body\t{}\t\t\t{}", name, parts);
    }
}
