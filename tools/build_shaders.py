#!/usr/bin/env python3
"""[U-501] src/client/shaders/*.frag → SPIR-V (glslc) → src/client/shaders/shaders_spv.hpp (committed, so building the
game needs no shader compiler). Run it after changing a shader:  python3 tools/build_shaders.py"""
import struct
import subprocess
import tempfile
from pathlib import Path

DIR = Path(__file__).resolve().parents[1] / "src" / "client" / "shaders"
out = ["#pragma once", "// generated by tools/build_shaders.py from *.frag — do not edit", "#include <cstdint>", "", "namespace em::shaders {", ""]
for f in sorted(DIR.glob("*.frag")):
    with tempfile.TemporaryDirectory() as t:
        spv = Path(t) / "x.spv"
        subprocess.run(["glslc", "-O", "--target-env=vulkan1.0", "-fshader-stage=frag", str(f), "-o", str(spv)], check=True)
        b = spv.read_bytes()
    words = struct.unpack(f"<{len(b) // 4}I", b)
    out.append(f"inline constexpr std::uint32_t k_{f.stem}[] = {{")
    for i in range(0, len(words), 12):
        out.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 12]) + ",")
    out += ["};", ""]
out.append("}  // namespace em::shaders")
(DIR / "shaders_spv.hpp").write_text("\n".join(out) + "\n")
print("wrote", DIR / "shaders_spv.hpp")
